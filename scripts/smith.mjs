const TOOLCHAIN = () => {
  if (!toolchain) {
    const clang = execFileSync("xcrun", ["--find", "clang"]).toString().trim();
    toolchain = { CC: clang, AR: join(dirname(clang), "ar"), CARGO_TARGET_AARCH64_APPLE_DARWIN_LINKER: clang, SDKROOT: execFileSync("xcrun", ["--show-sdk-path"]).toString().trim() };
  }
  return toolchain;
};
/** sha256 over a tree: every file's relative path, size and bytes in sorted order; .git and target skipped. */
export function treeHash(dir) {
  const h = createHash("sha256");
  let files = 0;
  const walk = (rel) => {
    for (const name of readdirSync(join(dir, rel)).sort()) {
      if (name === ".git" || name === "target") continue;
      const r = rel ? `${rel}/${name}` : name;
      const st = lstatSync(join(dir, r));
      if (st.isSymbolicLink()) {
        // A link is hashed as its target text, and must stay inside the tree.
        const t = readlinkSync(join(dir, r));
        if (t.startsWith("/") || join(rel, t).startsWith("..")) throw new Error(`${dir}/${r} links outside the tree`);
        h.update(`${r}\0link\0${t}`);
        files++;
      } else if (st.isDirectory()) walk(r);
      else {
        const b = readFileSync(join(dir, r));
        h.update(`${r}\0${b.length}\0`);
        h.update(b);
        files++;
      }
    }
  };
  walk("");
  return { sha256: h.digest("hex"), files };
}
const MANIFEST = join(SMITH, "vendor-manifest.json");
function checkTree(rel) {
  const want = readJson(MANIFEST)[rel];
  const got = treeHash(join(ROOT, rel));
  if (!want || got.sha256 !== want.sha256 || got.files !== want.files) throw new Error(`${ROOT}/${rel} is not the tree in zk/smith/vendor-manifest.json (${got.files} files, ${got.sha256.slice(0, 16)}..)`);
}

