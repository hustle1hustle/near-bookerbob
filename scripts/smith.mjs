#!/usr/bin/env node
// The Jolt smith (docs/smith.md): a NEAR AI model writes a Jolt guest on a swarm agent's
// request, from a fixed skeleton, and a checker decides whether it may be built and registered.
//
//   node scripts/smith.mjs spec  <id>     the request: spec hash, resolved vectors, encodings
//   node scripts/smith.mjs write <id>     NEAR AI writes body.rs + adversarial vectors (E2EE, TEE-signed)
//   node scripts/smith.mjs gen   <id>     static check of body.rs, generate the crate from the template
//   node scripts/smith.mjs build <id>     at the fixed root: compile, every vector natively and in the guest, prove
//   node scripts/smith.mjs run   <id>     write, gen, build; on a failed check the model gets the errors (3 tries)
//
// Spec: zk/smith/specs/<id>.json. Output: zk/smith/programs/<id>/ (crate, smith/ authorship
// capture, vectors.json, out/ proof + verifier preprocessing + statement.json).
// Needs NEAR_AI_KEY or ~/.rep-secrets/near-ai.key for `write` (never logged); about $0.01 a call.
