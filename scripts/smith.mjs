/**
 * smith-host runs with HOME inside the build root. Jolt's Dory setup (crates/jolt-dory
 * scheme.rs) loads $HOME/.cache/dory/dory_<n>.urs, and writes a freshly OsRng-generated one when
 * it is missing; the verifier preprocessing embeds it, so it is part of the program hash. Every
 * run gets exactly the pinned files in zk/smith/urs (sha256 in SHA256SUMS), and a run that made a
 * new URS fails (pinUrs / checkUrs).
 */
const DORY = () => join(realpathSync(ROOT), "home/.cache/dory");
const PINNED = () => Object.fromEntries(readFileSync(join(SMITH, "urs/SHA256SUMS"), "utf8").trim().split("\n").map((l) => l.split(/\s+/)).map(([h, f]) => [f, h]));
function pinUrs() {
  mkdirSync(join(ROOT, "home"), { recursive: true });
  rmSync(DORY(), { recursive: true, force: true });
  mkdirSync(DORY(), { recursive: true });
  for (const [f, h] of Object.entries(PINNED())) {
    const b = readFileSync(join(SMITH, "urs", f));
    if (sha(b) !== h) throw new Error(`zk/smith/urs/${f} does not match SHA256SUMS`);
    writeFileSync(join(DORY(), f), b);
  }
}
function checkUrs() {
  const pinned = PINNED();
  for (const f of readdirSync(DORY()).filter((x) => x.endsWith(".urs"))) {
    if (!pinned[f]) throw new Error(`Dory generated a new URS (${f}): pin it in zk/smith/urs first, or the program hash is not reproducible`);
    if (sha(readFileSync(join(DORY(), f))) !== pinned[f]) throw new Error(`${f} changed during the run`);
  }
}
const hostEnv = () => (pinUrs(), {});

/** The wasm build of the model's code: at most this many 64 KiB pages of memory (64 MiB). */
const WASM_MAX_PAGES = 1024;
const WASM_TIMEOUT_MS = 20_000;

/** The module must import nothing and declare a memory maximum within the cap. */
export function wasmPolicy(bytes) {
  const problems = [];
  const mod = new WebAssembly.Module(bytes);
  const imports = WebAssembly.Module.imports(mod);
  if (imports.length) problems.push(`the wasm imports ${imports.map((i) => `${i.module}.${i.name}`).join(", ")}`);
  // Memory section (id 5): read each memory's limits.
  let o = 8;
  const leb = () => {
    let v = 0, s = 0, b;
    do {
      b = bytes[o++];
      v |= (b & 0x7f) << s;
      s += 7;
    } while (b & 0x80);
    return v >>> 0;
  };
  let mems = 0;
  while (o < bytes.length) {
    const id = bytes[o++];
    const size = leb();
    const end = o + size;
    if (id === 5) {
      const n = leb();
      for (let i = 0; i < n; i++) {
        const flag = bytes[o++];
        leb();
        mems++;
        if (!(flag & 1)) problems.push("the wasm memory has no maximum");
        else if (leb() > WASM_MAX_PAGES) problems.push(`the wasm memory maximum is over ${WASM_MAX_PAGES} pages`);
      }
    }
    o = end;
  }
  if (mems !== 1) problems.push(`the wasm defines ${mems} memories`);
  return problems;
}

/** One vector in the wasm build, in a worker with a time limit and a JS heap cap. */
export function runWasm(bytes, publicHex, privateHex) {
  const code = `
    const { parentPort, workerData: d } = require("node:worker_threads");
    (async () => {
      try {
        const x = (await WebAssembly.instantiate(d.bytes, {})).instance.exports;
        const put = (h) => { const b = Buffer.from(h, "hex"); const p = x.h_alloc(b.length); new Uint8Array(x.memory.buffer, p, b.length).set(b); return [p, b.length]; };
        const n = x.h_commit(...put(d.pub), ...put(d.priv));
        const out = Buffer.from(new Uint8Array(x.memory.buffer, x.h_out_ptr(), n));
        parentPort.postMessage(out[0] === 1 ? { ok: true, spec: out.subarray(1, 33).toString("hex"), commitment: out.subarray(33, 65).toString("hex"), output: out.subarray(65).toString("hex") } : { ok: false, reason: out.subarray(1).toString() });
      } catch (e) {
        parentPort.postMessage({ ok: false, reason: "trapped: " + String(e.message).slice(0, 80) });
      }
    })();`;
  return new Promise((resolve) => {
    const wk = new Worker(code, { eval: true, workerData: { bytes, pub: publicHex, priv: privateHex }, resourceLimits: { maxOldGenerationSizeMb: 128, maxYoungGenerationSizeMb: 32, stackSizeMb: 4 } });
    const t = setTimeout(() => (wk.terminate(), resolve({ ok: false, reason: `timed out after ${WASM_TIMEOUT_MS / 1000} s` })), WASM_TIMEOUT_MS);
    wk.once("message", (m) => (clearTimeout(t), wk.terminate(), resolve(m)));
    wk.once("error", (e) => (clearTimeout(t), resolve({ ok: false, reason: `worker: ${String(e.message).slice(0, 80)}` })));
  });
}

export const builtIds = () => readdirSync(join(SMITH, "programs")).filter((d) => existsSync(join(SMITH, "programs", d, "body/src/body.rs"))).sort();

async function cmdBuild(id, attemptDir) {
  const spec = loadSpec(id);
  const ids = [...new Set([...builtIds(), id])].sort();
  syncRoot(ids);
  // The lint runs again on the crate's body.rs before anything compiles it.
  const lintProblems = await staticCheck(readFileSync(join(progDir(id), "body/src/body.rs"), "utf8"));
  if (lintProblems.length) return { ok: false, stage: "static", errors: lintProblems.join("\n") };
  // The lock gains only the workspace's own path crates (cargo update -w); every registry and git
  // dependency stays at the committed version, and the build itself is --locked.
  const u = run(CARGO, ["update", "--offline", "--workspace"]);
  if (!u.ok) return { ok: false, stage: "lock", errors: u.out.slice(-2000) };
  const b = run(CARGO, ["build", "--offline", "--locked", "--release", "-p", "smith-host", "-j", JOBS]);
  cpSync(join(ROOT, "Cargo.lock"), join(SMITH, "Cargo.lock"));
  if (!b.ok) return { ok: false, stage: "compile", errors: b.out.split("\n").filter((l) => /^(error|warning: unused)|^\s+-->|^\s*\|/.test(l) || /error\[/.test(l)).slice(0, 80).join("\n") || b.out.slice(-4000) };
  // Every vector: the requester's, then the smith's.
  const req = await resolveVectors(spec, spec.vectors);
  let adv = [];
  const advPath = attemptDir ? join(attemptDir, "adversarial.json") : join(progDir(id), "vectors.json");
  const advRaw = attemptDir ? readJson(advPath) : readJson(advPath).filter((v) => v.by === "smith").map((v) => v.source);
  const advErrors = [];
  for (const v of advRaw) {
    try {
      adv.push(await resolveVector(spec, v, sha256, req));
    } catch (e) {
      advErrors.push(`adversarial vector "${v.label}" does not encode: ${e.message}`);
    }
  }
  const rows = [...req.map((v) => ({ ...hostVector(spec, v, "requester"), source: v })), ...adv.map((v) => ({ ...hostVector(spec, v, "smith"), source: v }))];
  const vpath = join(progDir(id), "vectors.json");
  writeJson(vpath, rows);
  const rootVectors = join(ROOT, `${id}.vectors.json`);
  cpSync(vpath, rootVectors);
  // The model's code runs only as wasm (no imports, capped memory) in a capped worker; the
  // guest runs in Jolt's emulator. Their results must agree on every vector.
  const w = run(CARGO, ["build", "--offline", "--locked", "--release", "--target", "wasm32-unknown-unknown", "-p", `smith-${id}-wasm`, "-j", JOBS], {
    env: { CARGO_TARGET_WASM32_UNKNOWN_UNKNOWN_RUSTFLAGS: `-C link-arg=--max-memory=${WASM_MAX_PAGES * 65536}` },
  });
  if (!w.ok) return { ok: false, stage: "compile", errors: w.out.split("\n").filter((l) => /^error|^\s+-->/.test(l)).slice(0, 40).join("\n") || w.out.slice(-3000) };
  const wasmBytes = readFileSync(join(ROOT, "target/wasm32-unknown-unknown/release", `smith_${crateName(id)}_wasm.wasm`));
  const wasmProblems = wasmPolicy(wasmBytes);
  if (wasmProblems.length) return { ok: false, stage: "wasm", errors: wasmProblems.join("\n") };
  const c = run(join(ROOT, "target/release/smith-host"), ["check", id, rootVectors], hostEnv());
  checkUrs();
  const last = c.out.trim().split("\n").filter((l) => l.startsWith("{")).pop();
  const traced = last ? JSON.parse(last) : null;
  const trim = (h) => h.replace(/(00)+$/, "");
  const report = traced && { id, rows: [] };
  if (traced) {
    for (const [i, r] of rows.entries()) {
      const g = traced.rows[i];
      const m = await runWasm(wasmBytes, r.public_hex, r.private_hex);
      const committed = m.ok ? hex(guestOutputs(unhex(m.spec), unhex(m.commitment), unhex(m.output))) : null;
      const agree = m.ok ? !g.guest_panic && trim(committed) === trim(g.guest_outputs) : g.guest_panic;
      const asExpected = r.expect === "refuse" ? !m.ok : m.ok && (!r.expect_output_hex || r.expect_output_hex === m.output);
      report.rows.push({ label: r.label, by: r.by, wasm: m.ok ? m.output : `refused: ${m.reason}`, guest_panic: g.guest_panic, cycles: g.cycles, wasm_equals_guest: agree, as_expected: asExpected });
      console.log(`${agree && asExpected ? "PASS" : "FAIL"}  ${r.label} (${m.ok ? m.output : `refused: ${m.reason}`})`);
    }
  }
  writeJson(join(progDir(id), "check.json"), { ...(report ?? {}), all: report?.rows.every((r) => r.wasm_equals_guest && r.as_expected), adversarial_encode_errors: advErrors, at: new Date().toISOString() });
  const reqFail = report?.rows.filter((r) => r.by === "requester" && !(r.wasm_equals_guest && r.as_expected)) ?? [];
  const advFail = report?.rows.filter((r) => r.by === "smith" && !(r.wasm_equals_guest && r.as_expected)) ?? [];
  const divergent = report?.rows.filter((r) => !r.wasm_equals_guest) ?? [];
  if (!report || reqFail.length || divergent.length || advFail.length || advErrors.length) {
    return { ok: false, stage: "vectors", errors: [!report ? c.out.slice(-3000) : "", ...advErrors, ...[...reqFail, ...advFail].map((r) => `FAIL ${r.by} vector "${r.label}": got ${r.wasm}, wasm equals guest ${r.wasm_equals_guest}`)].filter(Boolean).join("\n") };
  }
  // Prove the requester's vector marked prove.
  const pv = rows.find((r) => r.by === "requester" && r.source.prove);
  const outDir = join(progDir(id), "out");
  rmSync(outDir, { recursive: true, force: true });
  const vfile = join(ROOT, `${id}.prove.json`);
  writeJson(vfile, pv);
  const p = run("/usr/bin/time", ["-l", join(ROOT, "target/release/smith-host"), "prove", id, vfile, join(ROOT, "out", id)], hostEnv());
  checkUrs();
  if (!p.ok) return { ok: false, stage: "prove", errors: p.out.slice(-3000) };
  const native = readJson(join(ROOT, "out", id, "native.json"));
  const rss = Number(p.out.match(/(\d+)\s+maximum resident set size/)?.[1] ?? 0);
  mkdirSync(outDir, { recursive: true });
  for (const f of ["verifier.bin", "proof.bin", "guest.elf"]) cpSync(join(ROOT, "out", id, f), join(outDir, f));
  const outBytes = unhex(native.output_hex);
  const statement = {
    note: "What a verifier checks: the proof against the program hash (sha256 of verifier.bin), with the guest's input bytes rebuilt from `public` and its output bytes from (spec_hash, private_commitment, output). The private input is not here.",
    id,
    spec_hash: specHash(spec),
    program_hash: native.program_hash,
    public: pv.source.public,
    public_hex: pv.public_hex,
    private_commitment: native.private_commitment,
    output: decode(spec, "Output", outBytes),
    output_hex: native.output_hex,
  };
  // The page and the judge rebuild these bytes; check that they agree with the prover's io.
  const ins = hex(guestInputs(unhex(statement.public_hex)));
  const outs = hex(guestOutputs(unhex(statement.spec_hash), unhex(statement.private_commitment), outBytes));
  // Jolt pads the io with zero bytes and its verifier compares up to trailing zeros.
  if (trim(ins) !== trim(native.io_inputs_hex) || trim(outs) !== trim(native.io_outputs_hex)) throw new Error("the statement's rebuilt bytes differ from the prover's io");
  writeJson(join(outDir, "statement.json"), statement);
  writeJson(join(outDir, "result.json"), { ...native, peak_rss_bytes: rss, source_sha256: sourceHash(id), urs: PINNED(), at: new Date().toISOString() });
  console.log(`prove ${id}: program ${native.program_hash.slice(0, 16)}.., prove ${native.prove_s.toFixed(2)} s, verify ${native.verify_ms.toFixed(0)} ms, proof ${native.proof_bytes} B, refused ${native.refused.length} changed statements`);
  return { ok: true, statement };
}

