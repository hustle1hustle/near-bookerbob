/** Canonical JSON: keys sorted at every level, no spaces. The spec hash is sha256 of it. */
export function canonical(v) {
  if (Array.isArray(v)) return `[${v.map(canonical).join(",")}]`;
  if (v && typeof v === "object") return `{${Object.keys(v).sort().map((k) => `${JSON.stringify(k)}:${canonical(v[k])}`).join(",")}}`;
  return JSON.stringify(v);
}

export const loadSpec = (id) => readJson(join(SMITH, "specs", `${id}.json`));
export const specHash = (spec) => sha(Buffer.from(canonical(spec)));
const crateName = (id) => id.replace(/-/g, "_");
const progDir = (id) => join(SMITH, "programs", id);

// ---------- the template: types from the spec, never from the model ----------

const SCALAR = { u8: "u8", u16: "u16", u32: "u32", u64: "u64", u128: "u128", bool: "bool", bytes32: "[u8; 32]", string: "String", bytes: "Vec<u8>" };
function rustType(spec, t) {
  if (SCALAR[t]) return SCALAR[t];
  let m;
  if ((m = t.match(/^vec<(.+)>$/))) return `Vec<${rustType(spec, m[1])}>`;
  if ((m = t.match(/^option<(.+)>$/))) return `Option<${rustType(spec, m[1])}>`;
  if (spec.types?.[t] && /^[A-Z][A-Za-z0-9]*$/.test(t)) return t;
  throw new Error(`type not allowed: ${t}`);
}
const ident = (f) => {
  if (!/^[a-z][a-z0-9_]*$/.test(f) || ["type", "match", "fn", "mod", "use", "crate", "self", "super", "impl", "loop", "ref", "move"].includes(f)) throw new Error(`field name not allowed: ${f}`);
  return f;
};
export function typesRs(spec) {
  const struct = (name, fields) =>
    `#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]\npub struct ${name} {\n${fields.map(([f, t]) => `    pub ${ident(f)}: ${rustType(spec, t)},`).join("\n")}\n}\n`;
  for (const n of Object.keys(spec.types ?? {})) if (["Public", "Private", "Output"].includes(n)) throw new Error(`type name reserved: ${n}`);
  return [
    "//! Generated by scripts/smith.mjs from the request's spec; do not edit by hand.",
    "#![allow(unused_imports)]",
    "use alloc::string::String;",
    "use alloc::vec::Vec;",
    "use serde::{Deserialize, Serialize};",
    "",
    ...Object.entries(spec.types ?? {}).map(([n, f]) => struct(n, f)),
    "/// The public input: the verifier sees it.",
    struct("Public", spec.public),
    "/// The private input: untrusted advice, not in the verifier's inputs.",
    struct("Private", spec.private),
    "/// The output: the only thing the proof reveals beyond the public input.",
    struct("Output", spec.output),
  ].join("\n");
}

function render(tmpl, vars) {
  return tmpl.replace(/\{\{([A-Z_]+)\}\}/g, (_, k) => {
    if (!(k in vars)) throw new Error(`template variable ${k}`);
    return String(vars[k]);
  });
}

// ---------- the static check on the model's code ----------

/**
 * zk/smith/lint (syn with an item, path and macro allowlist), as wasm: the same check runs here
 * before anything compiles, in scripts/smith-check.mjs and in the page. One layer of three: the
 * body crate is no_std with unsafe forbidden on every target, and every build and run of model
 * code is inside zk/smith/sandbox.sb.
 */
export const LINT_WASM = join(REPO, "agents/smith/lint.wasm");
export const staticCheck = (body) => lint(body, readFileSync(LINT_WASM));

/** A spec that hides data must salt it: its private input carries a 32-byte salt field. */
export function validateSpec(spec) {
  const problems = [];
  if (spec.privacy && !spec.private.some(([f, t]) => f === "salt" && t === "bytes32")) problems.push("a privacy spec needs a `salt: bytes32` private field (the private commitment is sha256 of the private bytes)");
  typesRs(spec);
  return problems;
}

// ---------- vectors ----------

export async function resolveVectors(spec, list) {
  const out = [];
  for (const v of list) out.push(await resolveVector(spec, v, sha256, out));
  return out;
}

/** A vector as the host reads it: hex bytes and the expected output bytes. */
function hostVector(spec, v, by) {
  const row = {
    label: v.label,
    by,
    public_hex: hex(encode(spec, "Public", v.public)),
    private_hex: hex(encode(spec, "Private", v.private)),
    expect: v.expect === "refuse" ? "refuse" : "ok",
  };
  if (v.expect !== "refuse") row.expect_output_hex = hex(encode(spec, "Output", v.expect));
  return row;
}

// ---------- spec ----------

async function cmdSpec(id) {
  const spec = loadSpec(id);
  if (spec.id !== id) throw new Error("spec id differs from its file name");
  const vs = await resolveVectors(spec, spec.vectors);
  const rows = vs.map((v) => hostVector(spec, v, "requester"));
  console.log(JSON.stringify({ id, spec_hash: specHash(spec), types_rs_sha256: sha(typesRs(spec)), vectors: rows.map((r) => ({ label: r.label, expect: r.expect, public_bytes: r.public_hex.length / 2, private_bytes: r.private_hex.length / 2 })) }, null, 1));
  return { spec, vs, rows };
}

