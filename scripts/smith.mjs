/** POST with no header or body timeout (20 minutes overall); the exact response bytes. */
function postLong(url, headers, body) {
  return new Promise((resolve, reject) => {
    const req = httpsRequest(url, { method: "POST", headers: { ...headers, "Content-Length": body.length } }, (r) => {
      const chunks = [];
      r.on("data", (c) => chunks.push(c));
      r.on("end", () => resolve({ ok: r.statusCode >= 200 && r.statusCode < 300, status: r.statusCode, bytes: Buffer.concat(chunks) }));
      r.on("error", reject);
    });
    req.setTimeout(20 * 60_000, () => req.destroy(new Error("chat: no answer in 20 minutes")));
    req.on("error", reject);
    req.end(body);
  });
}

function parseAnswer(answer) {
  const rust = answer.match(/```rust\s*\n([\s\S]*?)```/);
  const json = answer.match(/```json\s*\n([\s\S]*?)```/);
  if (!rust || !json) throw new Error("the answer does not hold a ```rust and a ```json block");
  return { body: rust[1].trimEnd() + "\n", adversarial: JSON.parse(json[1]) };
}

async function cmdWrite(id, feedback, attempt) {
  const spec = loadSpec(id);
  const KEY = (process.env.NEAR_AI_KEY ?? readFileSync(`${process.env.HOME}/.rep-secrets/near-ai.key`, "utf8")).trim();
  const auth = { Authorization: `Bearer ${KEY}` };
  const nonce = randomBytes(32).toString("hex");
  const reportRes = await fetch(`${API}/attestation/report?model=${encodeURIComponent(MODEL)}&signing_algo=ed25519&nonce=${nonce}`, { headers: { ...auth, "x-no-aliasing": "true" } });
  const reportBytes = Buffer.from(await reportRes.arrayBuffer());
  if (!reportRes.ok) throw new Error(`attestation report HTTP ${reportRes.status}`);
  const report = JSON.parse(reportBytes);
  const ma = report.model_attestations?.[0];
  if (!ma?.signing_address || !/^[0-9a-f]{64}$/.test(ma.signing_address)) throw new Error(`no ed25519 model attestation for ${MODEL}`);
  const modelPub = ma.signing_address;
  if (ma.request_nonce !== nonce) throw new Error("the attestation report is not bound to our nonce");
  const { system, user } = prompt(spec, feedback);
  const me = clientKey();
  const sealedSystem = sealToWithKey(system, modelPub);
  const sealedUser = sealToWithKey(user, modelPub);
  const wireBody = { model: MODEL, max_tokens: 16000, temperature: 0, messages: [{ role: "system", content: sealedSystem.wire }, { role: "user", content: sealedUser.wire }] };
  const reqBytes = Buffer.from(JSON.stringify(wireBody));
  const t0 = Date.now();
  // The model can think for more than five minutes; node's fetch gives up on headers at 300 s.
  const res = await postLong(`${API}/chat/completions`, { ...auth, "Content-Type": "application/json", "X-Signing-Algo": "ed25519", "X-Client-Pub-Key": me.pubHex, "X-Model-Pub-Key": modelPub, "X-Encryption-Version": "2", "x-no-aliasing": "true" }, reqBytes);
  const resBytes = res.bytes;
  if (!res.ok) throw new Error(`chat HTTP ${res.status} ${resBytes.toString().slice(0, 300)}`);
  const body = JSON.parse(resBytes);
  const wire = body.choices[0].message.content;
  const answer = openWith(wire, me.xSecret);
  const sig = await (await fetch(`${API}/signature/${body.id}?model=${encodeURIComponent(MODEL)}&signing_algo=ed25519`, { headers: auth })).json();
  const [, sReq, sRes] = sig.text.split(":");
  if (!edVerify(sig.text, sig.signature, sig.signing_address) || sReq !== sha(reqBytes) || sRes !== sha(resBytes) || sig.signing_address !== modelPub) {
    throw new Error("the TEE signature does not cover these bytes with the attested key");
  }
  const dir = join(progDir(id), "smith", `attempt-${attempt}`);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "report.json"), reportBytes);
  writeFileSync(join(dir, "request.json"), reqBytes);
  writeFileSync(join(dir, "response.json"), resBytes);
  writeJson(join(dir, "signature.json"), sig);
  const capture = {
    note: "The smith's authorship: one sealed chat (E2EE v2) to the model's attested key, the report bound to our nonce; the TEE signature covers sha256 of the request and response wire bytes. request_keys open the two sealed prompt messages and response_key opens the answer field only, so anyone can read what was asked and the code the model wrote.",
    at: new Date().toISOString(),
    model: MODEL,
    nonce,
    chat_id: body.id,
    signing_address: modelPub,
    signed_text: sig.text,
    signature: sig.signature,
    request_sha256: sha(reqBytes),
    response_sha256: sha(resBytes),
    report_sha256: sha(reportBytes),
    response_key: fieldKey(wire, me.xSecret),
    // The keys for the two sealed request messages: anyone can open them and compare with the
    // prompt rebuilt from the spec (smith-check). The client secret is never written.
    request_keys: { system: sealedSystem.key, user: sealedUser.key },
    seconds: (Date.now() - t0) / 1000,
    usage: body.usage ?? null,
    prompt: { system, user },
    answer,
  };
  writeJson(join(dir, "capture.json"), capture);
  let parsed;
  try {
    parsed = parseAnswer(answer);
  } catch (e) {
    return { dir, error: String(e.message), answer };
  }
  writeFileSync(join(dir, "body.rs"), parsed.body);
  writeJson(join(dir, "adversarial.json"), parsed.adversarial);
  console.log(`write ${id}: attempt ${attempt}, ${MODEL}, chat ${body.id}, ${capture.seconds}s, body ${parsed.body.split("\n").length} lines, ${parsed.adversarial.length} adversarial vectors, signature verified`);
  return { dir, ...parsed };
}

// ---------- gen: the crate from the template ----------

/** The template files exactly as cmdGen renders them for this spec (smith-check compares). */
export function renderTemplate(spec) {
  const L = spec.limits;
  const h = specHash(spec);
  const vars = { ID: spec.id, CRATE: crateName(spec.id), SPEC_HASH_HEX: h, SPEC_HASH_BYTES: `[${h.match(/../g).map((x) => `0x${x}`).join(", ")}]`, HEAP: L.heap, MAX_INPUT: L.max_input, MAX_PRIVATE: L.max_private, MAX_OUTPUT: L.max_output, MAX_TRACE: L.max_trace };
  return Object.fromEntries([...TEMPLATE_FILES, ...CHECKER_FILES].map(([f, t]) => [f, render(readFileSync(join(SMITH, "template", t), "utf8"), vars)]));
}

async function cmdGen(id, attemptDir) {
  const spec = loadSpec(id);
  const specProblems = validateSpec(spec);
  if (specProblems.length) throw new Error(specProblems.join("; "));
  const body = readFileSync(join(attemptDir, "body.rs"), "utf8");
  const problems = await staticCheck(body);
  if (problems.length) return { ok: false, errors: problems.join("\n") };
  const L = spec.limits;
  const h = specHash(spec);
  const dir = progDir(id);
  const T = (f) => readFileSync(join(SMITH, "template", f), "utf8");
  rmSync(join(dir, "src"), { recursive: true, force: true });
  rmSync(join(dir, "body"), { recursive: true, force: true });
  mkdirSync(join(dir, "src"), { recursive: true });
  mkdirSync(join(dir, "body/src"), { recursive: true });
  const vars = {
    ID: id,
    CRATE: crateName(id),
    SPEC_HASH_HEX: h,
    SPEC_HASH_BYTES: `[${h.match(/../g).map((x) => `0x${x}`).join(", ")}]`,
    HEAP: L.heap,
    MAX_INPUT: L.max_input,
    MAX_PRIVATE: L.max_private,
    MAX_OUTPUT: L.max_output,
    MAX_TRACE: L.max_trace,
  };
  rmSync(join(dir, "wasm"), { recursive: true, force: true });
  mkdirSync(join(dir, "wasm/src"), { recursive: true });
  for (const [f, t] of [...TEMPLATE_FILES, ...CHECKER_FILES]) writeFileSync(join(dir, f), render(T(t), vars));
  writeFileSync(join(dir, "body/src/types.rs"), typesRs(spec));
  writeFileSync(join(dir, "body/src/body.rs"), body);
  writeFileSync(join(dir, "SPEC_SHA256"), h + "\n");
  return { ok: true };
}

/** Every crate file rendered from the template: (path in the program dir, template file). */
export const TEMPLATE_FILES = [
  ["Cargo.toml", "Cargo.toml.tmpl"],
  ["src/lib.rs", "lib.rs.tmpl"],
  ["src/main.rs", "main.rs"],
  ["body/Cargo.toml", "body-Cargo.toml.tmpl"],
  ["body/src/lib.rs", "body-lib.rs.tmpl"],
  ["body/src/smith_std.rs", "smith_std.rs"],
];
/** The checker's wasm harness, rendered from the template too; not part of the program's source. */
export const CHECKER_FILES = [
  ["wasm/Cargo.toml", "wasm-Cargo.toml.tmpl"],
  ["wasm/src/lib.rs", "wasm-lib.rs.tmpl"],
];
/** The two files that are not the template: types.rs (from the spec) and body.rs (the model's). */
export const SOURCE_FILES = [...TEMPLATE_FILES.map(([f]) => f), "body/src/types.rs", "body/src/body.rs"];

/** sha256 over the program's source files, in a fixed order: what a reader rebuilds from. */
export function sourceHash(id) {
  const dir = progDir(id);
  const h = createHash("sha256");
  for (const f of SOURCE_FILES) {
    const b = readFileSync(join(dir, f));
    h.update(`${f}\0${b.length}\0`);
    h.update(b);
  }
  return h.digest("hex");
}

// ---------- build: fixed root, checker, prove ----------

function programsRs(ids) {
  return `fn programs() -> Vec<Program> {\n    vec![\n${ids.map((id) => `        program!(smith_${crateName(id)}, "${id}"),`).join("\n")}\n    ]\n}\n`;
}

/**
 * The build root is a fixed path in world-writable /tmp (the path is inside every ELF, so it
 * cannot move per machine). Refuse to build unless it is a real directory (no symlink), owned
 * by this user with mode 0700, and every parent but /tmp is owned by root or this user.
 */
export function checkRoot() {
  if (!existsSync(ROOT)) mkdirSync(ROOT, { mode: 0o700 });
  const st = lstatSync(ROOT);
  const uid = process.getuid();
  if (st.isSymbolicLink() || !st.isDirectory()) throw new Error(`${ROOT} is not a real directory`);
  if (st.uid !== uid) throw new Error(`${ROOT} is not owned by this user`);
  if ((st.mode & 0o777) !== 0o700) throw new Error(`${ROOT} has mode ${(st.mode & 0o777).toString(8)}, not 700 (chmod 700 ${ROOT})`);
  let d = dirname(realpathSync(ROOT));
  for (;;) {
    const p = lstatSync(d);
    const isTmp = d === "/tmp" || d === "/private/tmp";
    if (!isTmp && p.uid !== 0 && p.uid !== uid) throw new Error(`${d} is owned by uid ${p.uid}`);
    if (!isTmp && p.mode & 0o002) throw new Error(`${d} is world-writable`);
    if (d === "/") break;
    d = dirname(d);
  }
}

function syncRoot(ids) {
  checkRoot();
  // Host program list and dependencies, generated.
  writeFileSync(join(SMITH, "host/src/programs.rs"), programsRs(ids));
  const hostToml = join(SMITH, "host/Cargo.toml");
  const t = readFileSync(hostToml, "utf8");
  const deps = ids.map((id) => `smith_${crateName(id)} = { package = "smith-${id}", path = "../programs/${id}" }`).join("\n");
  writeFileSync(hostToml, t.replace(/# @programs-begin[\s\S]*# @programs-end/, `# @programs-begin\n${deps}${deps ? "\n" : ""}# @programs-end`));
  if (!existsSync(join(ROOT, "vendor/jolt/Cargo.toml"))) {
    const src = process.env.SMITH_JOLT ?? join(REPO, "zk/browser/vendor/jolt");
    if (!existsSync(join(src, "Cargo.toml"))) throw new Error(`no patched Jolt at ${src}: run zk/browser/build.sh once (it fetches the pin into zk/browser/vendor/jolt) or set SMITH_JOLT`);
    execFileSync("rsync", ["-a", "--exclude", "target", "--exclude", ".git", `${src}/`, join(ROOT, "vendor/jolt/")]);
  }
  // No git here: the patched Jolt tree and the vendored crates are checked against tree hashes
  // committed in zk/smith/vendor-manifest.json (every file's path, size and bytes).
  checkTree("vendor/jolt");
  ensureVendor();
  checkTree("crates");
  if (sha(readFileSync(join(ROOT, ".cargo/config.toml"))) !== readJson(MANIFEST)[".cargo/config.toml"].sha256) throw new Error(`${ROOT}/.cargo/config.toml is not the one in zk/smith/vendor-manifest.json`);
  // Only the programs in `ids` are in the root's workspace.
  execFileSync("rsync", ["-a", "--delete", "--exclude", "/target", "--exclude", "/vendor", "--exclude", "/out", "--exclude", "/programs/*/smith", "--exclude", "/programs/*/out", "--exclude", "/lint/target", "--exclude", "/target-zk", "--exclude", "/out-zk", "--exclude", "/home", "--exclude", "/evil-probe", "--exclude", "/crates", "--exclude", "/.cargo", "--exclude", "/cargo-home", "--exclude", "/tmp", "--exclude", "*.bak", `${SMITH}/`, `${ROOT}/`]);
  // rsync -a copies the source directory's mode onto the root; keep it 0700.
  chmodSync(ROOT, 0o700);
  for (const d of readdirSync(join(ROOT, "programs"))) if (!ids.includes(d)) rmSync(join(ROOT, "programs", d), { recursive: true, force: true });
}

/**
 * Every step that compiles or runs model-written code runs here: inside zk/smith/sandbox.sb (no
 * network, no reads under $HOME but the toolchains, writes only to the build root), offline and
 * --locked for cargo.
 */
function run(cmd, args, opts = {}) {
  const root = realpathSync(ROOT);
  // The sandbox may write inside these but not create, rename or remove them, so they exist first.
  for (const d of ["tmp", "cargo-home", "target", "target-zk", "out", "out-zk", "home"]) {
    const p = join(root, d);
    mkdirSync(p, { recursive: true });
    const st = lstatSync(p);
    if (st.isSymbolicLink() || !st.isDirectory() || st.uid !== process.getuid()) throw new Error(`${p} is not a real directory of this user`);
  }
  // A cargo config planted in CARGO_HOME would steer the next cargo step: refuse to start.
  const planted = readdirSync(join(root, "cargo-home")).filter((f) => /^config/.test(f));
  if (planted.length) throw new Error(`${root}/cargo-home holds ${planted.join(", ")}: refusing to run cargo (remove it and look at how it got there)`);
  const sandbox = ["-f", join(SMITH, "sandbox.sb"), "-D", `HOME=${process.env.HOME}`, "-D", `ROOT=${root}`, "-D", `TMP=${join(root, "tmp")}`, "-D", `XCODE_BIN=${dirname(TOOLCHAIN().CC)}`];
  const env = {
    PATH: `${join(process.env.HOME, ".cargo/bin")}:/usr/bin:/bin`,
    RUSTUP_HOME: join(process.env.HOME, ".rustup"),
    CARGO_HOME: join(root, "cargo-home"),
    TMPDIR: join(root, "tmp"),
    HOME: join(root, "home"),
    ...TOOLCHAIN(),
    ...(opts.env ?? {}),
  };
  // Every sandboxed step has a wall-clock limit (a compile that never ends is killed).
  const r = spawnSync("sandbox-exec", [...sandbox, cmd, ...args], { cwd: ROOT, encoding: "utf8", maxBuffer: 256 << 20, timeout: STEP_TIMEOUT_MS, killSignal: "SIGKILL", ...opts, env });
  if (r.error?.code === "ETIMEDOUT") return { ok: false, out: `killed after ${STEP_TIMEOUT_MS / 60000} minutes` };
  return { ok: r.status === 0, out: (r.stdout ?? "") + (r.stderr ?? "") };
}
