#!/usr/bin/env python3
"""Write GapIR/Pin.lean from the generated body.rs files, or (--check) verify that each file is
byte-for-byte the character list pinned there. The Lean side proves `emitT prog = .ok <list>` in
the kernel; this script is the only link from that list to the file bytes (ASCII, one char = one byte)."""
import sys, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
PROGS = [("coalition", "Coalition.prog", "out/body.rs"), ("spendBucket", "SpendBucket.prog", "out/spend-bucket.body.rs")]

def chars_lit(b: bytes) -> str:
    assert all(0x20 <= c < 0x7f or c == 0x0a for c in b), "printer output must be printable ASCII + newline"
    def ch(c):
        return "'\\n'" if c == 10 else "'\\''" if c == 39 else "'\\\\'" if c == 92 else f"'{chr(c)}'"
    return "[" + ", ".join(ch(c) for c in b) + "]"

def parse(lit: str) -> bytes:
    out = []
    for m in re.finditer(r"'(\\n|\\'|\\\\|[^'\\])'", lit):
        s = m.group(1)
        out.append(10 if s == "\\n" else 39 if s == "\\'" else 92 if s == "\\\\" else ord(s))
    return bytes(out)

pin = ROOT / "GapIR/Pin.lean"
if "--check" in sys.argv:
    src = pin.read_text()
    ok = True
    for name, _, path in PROGS:
        m = re.search(rf"def {name}Body : List Char :=\n  (\[.*?\])\n", src, re.S)
        same = m and parse(m.group(1)) == (ROOT / path).read_bytes()
        print(("same " if same else "DIFF ") + path)
        ok = ok and bool(same)
    sys.exit(0 if ok else 1)

parts = ["""import GapIR.Emit
import GapIR.Coalition
import GapIR.SpendBucket
/-! The emitted text, pinned in the kernel. For each program, `emitT prog` (the printer, run by the
kernel, not by compiled code) equals a literal character list, and `tools/pin.py --check` checks
that list is byte-for-byte the body.rs file. Generated by `tools/pin.py`; do not edit by hand. -/
namespace GapIR.Pin
open GapIR
"""]
for name, prog, path in PROGS:
    parts.append(f"""
def {name}Body : List Char :=
  {chars_lit((ROOT / path).read_bytes())}

theorem emit_{name}_opt : (Emit.emitT {prog}).toOption = some {name}Body := by decide +kernel

theorem emit_{name} : Emit.emitT {prog} = .ok {name}Body := by
  have h := emit_{name}_opt
  revert h; cases Emit.emitT {prog} <;> simp [Except.toOption]
""")
parts.append("""
#print axioms emit_coalition
#print axioms emit_spendBucket

end GapIR.Pin
""")
pin.write_text("".join(parts))
print("wrote", pin)
